/**
 * codeExporter.js
 * Generates standalone, compile-ready C and Python scanner code from the Minimized DFA.
 */

export function exportToC(minDFA, tokenNames) {
  const numStates = minDFA.states.size;
  const startStateId = minDFA.startState ? minDFA.startState.id : 0;
  const tokens = Array.from(new Set(tokenNames)).sort();

  const lines = [];
  lines.push("/*");
  lines.push(" * Standalone C Lexer generated by Regex to DFA Lexer Generator");
  lines.push(" * Compile with: gcc -O2 -o lexer lexer.c");
  lines.push(" */\n");
  lines.push("#include <stdio.h>");
  lines.push("#include <stdlib.h>");
  lines.push("#include <string.h>");
  lines.push("#include <stdbool.h>\n");

  lines.push(`#define NUM_STATES ${numStates}`);
  lines.push(`#define START_STATE ${startStateId}\n`);

  lines.push("typedef enum {");
  lines.push("    TOKEN_UNKNOWN = 0,");
  tokens.forEach(t => lines.push(`    TOKEN_${t},`));
  lines.push("    TOKEN_ERROR");
  lines.push("} TokenType;\n");

  lines.push("static const char* TOKEN_NAMES[] = {");
  lines.push('    "UNKNOWN",');
  tokens.forEach(t => lines.push(`    "${t}",`));
  lines.push('    "ERROR"');
  lines.push("};\n");

  lines.push("typedef struct {");
  lines.push("    bool is_accept;");
  lines.push("    TokenType token;");
  lines.push("    bool is_ignored;");
  lines.push("} StateInfo;\n");

  lines.push("static const StateInfo STATES[NUM_STATES] = {");
  for (let sid = 0; sid < numStates; sid++) {
    const st = minDFA.states.get(sid);
    if (st && st.isAccept) {
      lines.push(`    /* ${sid} (${st.label}) */ { true, TOKEN_${st.tokenName}, ${st.isIgnored ? 'true' : 'false'} },`);
    } else {
      lines.push(`    /* ${sid} */ { false, TOKEN_UNKNOWN, false },`);
    }
  }
  lines.push("};\n");

  lines.push("static int get_next_state(int state, unsigned char c) {");
  lines.push("    switch (state) {");
  for (const [sid, st] of Array.from(minDFA.states.entries()).sort((a,b) => a[0] - b[0])) {
    if (st.transitions.size === 0) continue;
    lines.push(`        case ${sid}:`);
    lines.push("            switch (c) {");

    const tgtToChars = new Map();
    for (const [sym, tgt] of st.transitions.entries()) {
      if (!tgtToChars.has(tgt.id)) tgtToChars.set(tgt.id, []);
      tgtToChars.get(tgt.id).push(sym);
    }

    for (const [tid, syms] of tgtToChars.entries()) {
      syms.forEach(s => {
        if (s === '\n') lines.push("                case '\\n':");
        else if (s === '\t') lines.push("                case '\\t':");
        else if (s === '\r') lines.push("                case '\\r':");
        else if (s === '\\') lines.push("                case '\\\\':");
        else if (s === '\'') lines.push("                case '\\'':");
        else lines.push(`                case '${s}':`);
      });
      lines.push(`                    return ${tid};`);
    }
    lines.push("                default: return -1;");
    lines.push("            }");
  }
  lines.push("        default: return -1;");
  lines.push("    }");
  lines.push("}\n");

  lines.push(`void tokenize(const char* input) {
    int pos = 0;
    int len = (int)strlen(input);
    int line = 1, col = 1;

    printf("=== Tokenizing with Maximal Munch ===\\n");

    while (pos < len) {
        int state = START_STATE;
        int scan_pos = pos;
        int last_accept_pos = -1;
        TokenType last_token = TOKEN_UNKNOWN;
        bool last_ignored = false;

        if (STATES[state].is_accept) {
            last_accept_pos = scan_pos;
            last_token = STATES[state].token;
            last_ignored = STATES[state].is_ignored;
        }

        while (scan_pos < len) {
            unsigned char c = (unsigned char)input[scan_pos];
            int next_state = get_next_state(state, c);
            if (next_state == -1) break;

            state = next_state;
            scan_pos++;

            if (STATES[state].is_accept) {
                last_accept_pos = scan_pos;
                last_token = STATES[state].token;
                last_ignored = STATES[state].is_ignored;
            }
        }

        if (last_accept_pos > pos) {
            int lexeme_len = last_accept_pos - pos;
            char* lexeme = (char*)malloc(lexeme_len + 1);
            strncpy(lexeme, input + pos, lexeme_len);
            lexeme[lexeme_len] = '\\0';

            if (!last_ignored) {
                printf("%-12s: \\"%s\\" [line %d, col %d]\\n", TOKEN_NAMES[last_token], lexeme, line, col);
            }

            for (int i = pos; i < last_accept_pos; i++) {
                if (input[i] == '\\n') { line++; col = 1; }
                else { col++; }
            }
            free(lexeme);
            pos = last_accept_pos;
        } else {
            printf("LEXICAL ERROR: Unexpected char '%c' [line %d, col %d]\\n", input[pos], line, col);
            if (input[pos] == '\\n') { line++; col = 1; }
            else { col++; }
            pos++;
        }
    }
    printf("=== Lexical Analysis Complete ===\\n");
}

int main(int argc, char** argv) {
    const char* sample = "if (count1 >= 42) return 3.14;";
    if (argc > 1) {
        sample = argv[1];
    }
    printf("Input: %s\\n\\n", sample);
    tokenize(sample);
    return 0;
}
`);

  return lines.join('\n');
}

export function exportToPython(minDFA, tokenNames) {
  const startStateId = minDFA.startState ? minDFA.startState.id : 0;
  const lines = [];

  lines.push('"""');
  lines.push('Standalone Python Lexer generated by Regex to DFA Lexer Generator');
  lines.push('"""\n');
  lines.push('import sys\n');

  lines.push(`START_STATE = ${startStateId}\n`);
  lines.push('# state_id: (is_accept, token_name, is_ignored)');
  lines.push('STATES = {');
  for (const [sid, st] of Array.from(minDFA.states.entries()).sort((a,b) => a[0] - b[0])) {
    if (st.isAccept) {
      lines.push(`    ${sid}: (True, "${st.tokenName}", ${st.isIgnored ? 'True' : 'False'}),`);
    } else {
      lines.push(`    ${sid}: (False, None, False),`);
    }
  }
  lines.push('}\n');

  lines.push('# (state_id, char) -> next_state_id');
  lines.push('TRANSITIONS = {');
  for (const [sid, st] of Array.from(minDFA.states.entries()).sort((a,b) => a[0] - b[0])) {
    for (const [sym, tgt] of st.transitions.entries()) {
      lines.push(`    (${sid}, ${JSON.stringify(sym)}): ${tgt.id},`);
    }
  }
  lines.push('}\n');

  lines.push(`def tokenize(source_code):
    pos = 0
    n = len(source_code)
    line, col = 1, 1
    tokens = []
    errors = []

    while pos < n:
        state = START_STATE
        scan_pos = pos
        last_accept_pos = None
        last_accept_tok = None
        last_ignored = False

        if STATES[state][0]:
            last_accept_pos = scan_pos
            last_accept_tok = STATES[state][1]
            last_ignored = STATES[state][2]

        while scan_pos < n:
            c = source_code[scan_pos]
            next_state = TRANSITIONS.get((state, c))
            if next_state is None:
                break
            state = next_state
            scan_pos += 1

            if STATES[state][0]:
                last_accept_pos = scan_pos
                last_accept_tok = STATES[state][1]
                last_ignored = STATES[state][2]

        if last_accept_pos is not None and last_accept_pos > pos:
            lexeme = source_code[pos:last_accept_pos]
            if not last_ignored:
                tokens.append((last_accept_tok, lexeme, line, col))
            for ch in lexeme:
                if ch == '\\n':
                    line += 1
                    col = 1
                else:
                    col += 1
            pos = last_accept_pos
        else:
            err_ch = source_code[pos]
            errors.append((err_ch, line, col))
            if err_ch == '\\n':
                line += 1
                col = 1
            else:
                col += 1
            pos += 1

    return tokens, errors

if __name__ == "__main__":
    sample = sys.argv[1] if len(sys.argv) > 1 else "if (count1 >= 42) return 3.14;"
    print(f"Scanning: {sample}\\n")
    tokens, errors = tokenize(sample)
    print("TOKENS:")
    for tok, lex, ln, cl in tokens:
        print(f"  {tok:<12}: {repr(lex)} [line {ln}, col {cl}]")
    if errors:
        print("\\nERRORS:")
        for ch, ln, cl in errors:
            print(f"  Lexical error on {repr(ch)} at line {ln}, col {cl}")
`);

  return lines.join('\n');
}
