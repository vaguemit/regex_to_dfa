"""
code_exporter.py
Exports the generated Minimized DFA into standalone, compile-ready C and Python scanner code.
"""

def export_to_c(min_dfa, token_names):
    """
    Generates a complete, self-contained C scanner (lexer.c).
    Uses a transition function and state tables implementing maximal munch.
    """
    num_states = len(min_dfa.states)
    start_state_id = min_dfa.start_state.id if min_dfa.start_state else 0

    # Build unique tokens list
    tokens = sorted(list(set(token_names)))

    c_code = []
    c_code.append("/*")
    c_code.append(" * Standalone C Lexer generated by Regex to DFA Lexer Generator")
    c_code.append(" * Compile with: gcc -O2 -o lexer lexer.c")
    c_code.append(" */\n")
    c_code.append("#include <stdio.h>")
    c_code.append("#include <stdlib.h>")
    c_code.append("#include <string.h>")
    c_code.append("#include <stdbool.h>\n")

    c_code.append(f"#define NUM_STATES {num_states}")
    c_code.append(f"#define START_STATE {start_state_id}\n")

    # Enum for Tokens
    c_code.append("typedef enum {")
    c_code.append("    TOKEN_UNKNOWN = 0,")
    for t in tokens:
        c_code.append(f"    TOKEN_{t},")
    c_code.append("    TOKEN_ERROR")
    c_code.append("} TokenType;\n")

    # Token name strings
    c_code.append("static const char* TOKEN_NAMES[] = {")
    c_code.append('    "UNKNOWN",')
    for t in tokens:
        c_code.append(f'    "{t}",')
    c_code.append('    "ERROR"')
    c_code.append("};\n")

    # State acceptance info
    c_code.append("typedef struct {")
    c_code.append("    bool is_accept;")
    c_code.append("    TokenType token;")
    c_code.append("    bool is_ignored;")
    c_code.append("} StateInfo;\n")

    c_code.append("static const StateInfo STATES[NUM_STATES] = {")
    for sid in range(num_states):
        st = min_dfa.states.get(sid)
        if st and st.is_accept:
            tok_enum = f"TOKEN_{st.token_name}"
            ign = "true" if st.is_ignored else "false"
            c_code.append(f"    /* {sid} ({st.label}) */ {{ true, {tok_enum}, {ign} }},")
        else:
            c_code.append(f"    /* {sid} */ {{ false, TOKEN_UNKNOWN, false }},")
    c_code.append("};\n")

    # Transition switch function
    c_code.append("static int get_next_state(int state, unsigned char c) {")
    c_code.append("    switch (state) {")
    for sid, st in sorted(min_dfa.states.items()):
        if not st.transitions:
            continue
        c_code.append(f"        case {sid}:")
        c_code.append("            switch (c) {")
        # Group by target state
        tgt_to_chars = {}
        for sym, tgt in st.transitions.items():
            tgt_to_chars.setdefault(tgt.id, []).append(sym)

        for tid, syms in tgt_to_chars.items():
            for s in syms:
                if s == '\n':
                    c_code.append("                case '\\n':")
                elif s == '\t':
                    c_code.append("                case '\\t':")
                elif s == '\r':
                    c_code.append("                case '\\r':")
                elif s == '\\':
                    c_code.append("                case '\\\\':")
                elif s == '\'':
                    c_code.append("                case '\\'':")
                else:
                    c_code.append(f"                case '{s}':")
            c_code.append(f"                    return {tid};")
        c_code.append("                default: return -1;")
        c_code.append("            }")
    c_code.append("        default: return -1;")
    c_code.append("    }")
    c_code.append("}\n")

    # Maximal Munch Scanner Implementation
    c_code.append("""void tokenize(const char* input) {
    int pos = 0;
    int len = (int)strlen(input);
    int line = 1, col = 1;

    printf("=== Tokenizing with Maximal Munch ===\\n");

    while (pos < len) {
        int state = START_STATE;
        int scan_pos = pos;
        int last_accept_pos = -1;
        TokenType last_token = TOKEN_UNKNOWN;
        bool last_ignored = false;

        if (STATES[state].is_accept) {
            last_accept_pos = scan_pos;
            last_token = STATES[state].token;
            last_ignored = STATES[state].is_ignored;
        }

        while (scan_pos < len) {
            unsigned char c = (unsigned char)input[scan_pos];
            int next_state = get_next_state(state, c);
            if (next_state == -1) break;

            state = next_state;
            scan_pos++;

            if (STATES[state].is_accept) {
                last_accept_pos = scan_pos;
                last_token = STATES[state].token;
                last_ignored = STATES[state].is_ignored;
            }
        }

        if (last_accept_pos > pos) {
            int lexeme_len = last_accept_pos - pos;
            char* lexeme = (char*)malloc(lexeme_len + 1);
            strncpy(lexeme, input + pos, lexeme_len);
            lexeme[lexeme_len] = '\\0';

            if (!last_ignored) {
                printf("%-12s: \\"%s\\" [line %d, col %d]\\n", TOKEN_NAMES[last_token], lexeme, line, col);
            }

            // Update line and column
            for (int i = pos; i < last_accept_pos; i++) {
                if (input[i] == '\\n') { line++; col = 1; }
                else { col++; }
            }
            free(lexeme);
            pos = last_accept_pos;
        } else {
            printf("LEXICAL ERROR: Unexpected char '%c' [line %d, col %d]\\n", input[pos], line, col);
            if (input[pos] == '\\n') { line++; col = 1; }
            else { col++; }
            pos++;
        }
    }
    printf("=== Lexical Analysis Complete ===\\n");
}

int main(int argc, char** argv) {
    const char* sample = "if (count1 >= 42) return 3.14;";
    if (argc > 1) {
        sample = argv[1];
    }
    printf("Input: %s\\n\\n", sample);
    tokenize(sample);
    return 0;
}
""")

    return "\n".join(c_code)


def export_to_python(min_dfa, token_names):
    """
    Generates a self-contained standalone Python scanner (lexer.py).
    """
    num_states = len(min_dfa.states)
    start_state_id = min_dfa.start_state.id if min_dfa.start_state else 0

    py_code = []
    py_code.append('"""')
    py_code.append('Standalone Python Lexer generated by Regex to DFA Lexer Generator')
    py_code.append('"""\n')
    py_code.append('import sys\n')

    # Transitions dictionary
    py_code.append(f'START_STATE = {start_state_id}\n')
    py_code.append('# state_id: (is_accept, token_name, is_ignored)')
    py_code.append('STATES = {')
    for sid, st in sorted(min_dfa.states.items()):
        if st.is_accept:
            py_code.append(f'    {sid}: (True, "{st.token_name}", {st.is_ignored}),')
        else:
            py_code.append(f'    {sid}: (False, None, False),')
    py_code.append('}\n')

    py_code.append('# (state_id, char) -> next_state_id')
    py_code.append('TRANSITIONS = {')
    for sid, st in sorted(min_dfa.states.items()):
        for sym, tgt in st.transitions.items():
            sym_repr = repr(sym)
            py_code.append(f'    ({sid}, {sym_repr}): {tgt.id},')
    py_code.append('}\n')

    py_code.append("""def tokenize(source_code):
    pos = 0
    n = len(source_code)
    line, col = 1, 1
    tokens = []
    errors = []

    while pos < n:
        state = START_STATE
        scan_pos = pos
        last_accept_pos = None
        last_accept_tok = None
        last_ignored = False

        if STATES[state][0]:
            last_accept_pos = scan_pos
            last_accept_tok = STATES[state][1]
            last_ignored = STATES[state][2]

        while scan_pos < n:
            c = source_code[scan_pos]
            next_state = TRANSITIONS.get((state, c))
            if next_state is None:
                break
            state = next_state
            scan_pos += 1

            if STATES[state][0]:
                last_accept_pos = scan_pos
                last_accept_tok = STATES[state][1]
                last_ignored = STATES[state][2]

        if last_accept_pos is not None and last_accept_pos > pos:
            lexeme = source_code[pos:last_accept_pos]
            if not last_ignored:
                tokens.append((last_accept_tok, lexeme, line, col))
            for ch in lexeme:
                if ch == '\\n':
                    line += 1
                    col = 1
                else:
                    col += 1
            pos = last_accept_pos
        else:
            err_ch = source_code[pos]
            errors.append((err_ch, line, col))
            if err_ch == '\\n':
                line += 1
                col = 1
            else:
                col += 1
            pos += 1

    return tokens, errors

if __name__ == "__main__":
    sample = sys.argv[1] if len(sys.argv) > 1 else "if (count1 >= 42) return 3.14;"
    print(f"Scanning: {sample}\\n")
    tokens, errors = tokenize(sample)
    print("TOKENS:")
    for tok, lex, ln, cl in tokens:
        print(f"  {tok:<12}: {repr(lex)} [line {ln}, col {cl}]")
    if errors:
        print("\\nERRORS:")
        for ch, ln, cl in errors:
            print(f"  Lexical error on {repr(ch)} at line {ln}, col {cl}")
""")

    return "\n".join(py_code)
